#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const file = args.find((arg) => !arg.startsWith("--"));
const minImagesArg = args.find((arg) => arg.startsWith("--min-images="));
const minImageBytesArg = args.find((arg) => arg.startsWith("--min-image-bytes="));
const minImages = minImagesArg ? Number(minImagesArg.split("=")[1]) : 0;
const minImageBytes = minImageBytesArg ? Number(minImageBytesArg.split("=")[1]) : 0;
const requireLocalImages = args.includes("--require-local-images");

if (!file) {
  console.error("Usage: node validate-waterfall-deck.mjs path/to/index.html [--min-images=N] [--require-local-images] [--min-image-bytes=N]");
  process.exit(2);
}

const html = fs.readFileSync(file, "utf8");
const errors = [];
const warnings = [];

if (!html.startsWith("<!-- Generated by Trae Work -->\n")) {
  errors.push('HTML must start with "<!-- Generated by Trae Work -->" on line 1 for Trae rendering.');
}

function count(pattern) {
  return (html.match(pattern) || []).length;
}

function stripTags(value) {
  return value.replace(/<[^>]*>/g, "").replace(/\s+/g, " ").trim();
}

function visibleLength(value) {
  return value.replace(/\s+/g, "").length;
}

const cardMatches = [...html.matchAll(/<article\b[^>]*class=["'][^"']*\bdeck-card\b[^"']*["'][^>]*>([\s\S]*?)<\/article>/gi)];
const totalCards = cardMatches.length;

if (totalCards === 0) errors.push("No <article class=\"deck-card\"> blocks found.");

cardMatches.forEach((match, index) => {
  const card = match[1];
  const n = index + 1;
  const frameCount = countIn(card, /<section\b[^>]*class=["'][^"']*\bslide-frame\b[^"']*["'][^>]*>/gi);
  const badgeCount = countIn(card, /<div\b[^>]*class=["'][^"']*\bpage-badge\b[^"']*["'][^>]*>/gi);
  const captionCount = countIn(card, /<details\b[^>]*class=["'][^"']*\bcaption\b[^"']*["'][^>]*>/gi);
  const stageCount = countIn(card, /<div\b[^>]*class=["'][^"']*\bslide-stage\b[^"']*["'][^>]*>/gi);
  const badgeText = card.match(/<div\b[^>]*class=["'][^"']*\bpage-badge\b[^"']*["'][^>]*>([\s\S]*?)<\/div>/i);
  const titleMatches = [...card.matchAll(/(<h[1-3]\b[^>]*class=["'][^"']*\bslide-title\b[^"']*["'][^>]*>)([\s\S]*?)<\/h[1-3]>/gi)];

  if (frameCount !== 1) errors.push(`Card ${n}: expected exactly one .slide-frame, found ${frameCount}.`);
  if (badgeCount !== 1) errors.push(`Card ${n}: expected exactly one .page-badge, found ${badgeCount}.`);
  if (stageCount !== 1) errors.push(`Card ${n}: expected exactly one .slide-stage, found ${stageCount}.`);
  if (captionCount !== 1) errors.push(`Card ${n}: expected exactly one details.caption, found ${captionCount}.`);

  if (!/<details\b[^>]*class=["'][^"']*\bcaption\b[^"']*["'][^>]*>[\s\S]*?<summary\b/i.test(card)) {
    errors.push(`Card ${n}: details.caption is missing a <summary>.`);
  }

  if (badgeText) {
    const text = stripTags(badgeText[1]);
    const expected = `${n}/${totalCards}`;
    if (text !== expected) errors.push(`Card ${n}: page badge is "${text}", expected "${expected}".`);
  }

  for (const titleMatch of titleMatches) {
    const titleTag = titleMatch[1] || "";
    const titleText = stripTags(titleMatch[2]);
    if (visibleLength(titleText) > 54 && !/\btitle-(md|sm)\b|--title-size|--title-width/i.test(titleTag)) {
      warnings.push(`Card ${n}: long slide title may need .title-md/.title-sm or local --title-width/--title-size tuning.`);
    }
  }

  const panelCount = countIn(card, /\bflow-panel\b/gi);
  if (panelCount >= 4 && !/\bflow-grid\b/i.test(card)) {
    warnings.push(`Card ${n}: ${panelCount} flow panels found outside .flow-grid; repeated blocks may feel crowded.`);
  }

  if (panelCount >= 4 && !/<div\b[^>]*class=["'][^"']*\bslide-content\b[^"']*["'][^>]*data-density=["'](?:compact|dense)["']/i.test(card)) {
    warnings.push(`Card ${n}: ${panelCount} flow panels may benefit from data-density="compact" or "dense".`);
  }
});

const cssMatch = html.match(/<style[^>]*>([\s\S]*?)<\/style>/i);
if (!cssMatch) {
  errors.push("No <style> block found.");
} else {
  const css = cssMatch[1];
  if (!/\.page-badge\s*\{[\s\S]*?opacity\s*:\s*0\b/i.test(css)) {
    errors.push(".page-badge must be hidden by default with opacity: 0.");
  }
  if (!/\.deck-card:hover\s+\.page-badge/i.test(css)) {
    errors.push("Missing hover reveal rule for .deck-card:hover .page-badge.");
  }
  if (!/\.deck-card:focus-within\s+\.page-badge/i.test(css)) {
    errors.push("Missing keyboard reveal rule for .deck-card:focus-within .page-badge.");
  }
  if (!/break-inside\s*:\s*avoid/i.test(css)) {
    warnings.push("No break-inside: avoid rule found; cards may split awkwardly in print/export.");
  }

  const requiredCssRules = [
    [/--page\s*:\s*#f1f1f0\b/i, "Missing fixed --page: #f1f1f0."],
    [/--card-radius\s*:\s*0px\b/i, "Slide cards must be square by default: --card-radius: 0px."],
    [/--badge\s*:\s*rgba\(28,\s*28,\s*28,\s*0\.34\)/i, "Page badge background must stay lightweight: rgba(28, 28, 28, 0.34)."],
    [/--caption-gap\s*:\s*clamp\(18px,\s*2\.4vw,\s*32px\)/i, "Caption spacing must use the standard --caption-gap clamp."],
    [/--slide-width\s*:\s*1600\b/i, "Fixed slide canvas must declare --slide-width: 1600."],
    [/--slide-height\s*:\s*900\b/i, "Fixed slide canvas must declare --slide-height: 900."],
    [/\.deck-shell\s*\{[\s\S]*?width\s*:\s*min\(1440px,\s*calc\(100%\s*-\s*48px\)\)/i, "Deck shell width must use the standard fit-width rule."],
    [/\.deck-card\s*\{[\s\S]*?margin\s*:\s*0\s*;/i, "Deck cards must not add vertical spacing; use caption padding instead."],
    [/\.caption\s*\{[\s\S]*?margin\s*:\s*0\s+16px\s*;[\s\S]*?padding\s*:\s*var\(--caption-gap\)\s+0\s*;[\s\S]*?color\s*:\s*#6b6b66\s*;[\s\S]*?font-size\s*:\s*clamp\(14px,\s*1\.05vw,\s*16px\)/i, "Caption style must preserve standard margin, symmetric padding, lighter color, and smaller type."],
    [/\.page-badge\s*\{[\s\S]*?font-size\s*:\s*clamp\(11px,\s*0\.9vw,\s*13px\)[\s\S]*?font-weight\s*:\s*500/i, "Page badge must keep lightweight type."],
    [/\.deck-shell\.compact-pages\s+\.caption/i, "Compact page-gap mode must be deck-level using .deck-shell.compact-pages .caption."],
  ];

  for (const [pattern, message] of requiredCssRules) {
    if (!pattern.test(css)) errors.push(message);
  }

  const columnCountValues = [...css.matchAll(/column-count\s*:\s*([^;]+)/gi)].map((match) => match[1].trim());
  const nonSingleColumnValues = columnCountValues.filter((value) => value !== "1");
  if (nonSingleColumnValues.length) {
    errors.push(`Waterfall decks must stay single-column; found column-count: ${nonSingleColumnValues.join(", ")}.`);
  }
}

if (/\[TITLE\]|\[SUBTITLE\]/.test(html)) {
  warnings.push("Template placeholders [TITLE] or [SUBTITLE] are still present.");
}

if (/deck-header|deck-title|deck-subtitle|deck-meta|Waterfall PPT/i.test(html)) {
  errors.push("Visible deck headers and Waterfall PPT labels are not allowed by the default waterfall template.");
}

if (!/ResizeObserver/.test(html) || !/--slide-scale/.test(html)) {
  warnings.push("No fixed-canvas ResizeObserver scaling found; slides may reflow with page width.");
}

if (/<script\b/i.test(html) && !/caption\.open|querySelectorAll\(["']\.caption/.test(html)) {
  warnings.push("Script tag found. Only fixed-canvas scaling and document-style page-gap interactions are expected by default.");
}

for (const tokenMatch of html.matchAll(/--(?:block-gap|block-pad|content-gap|section-gap)\s*:\s*([0-9.]+)px/gi)) {
  const value = Number.parseFloat(tokenMatch[1]);
  if (Number.isFinite(value) && value < 18) {
    warnings.push(`Internal spacing token ${tokenMatch[0]} is below the recommended comfort floor of 18px.`);
  }
}

const imageMatches = [...html.matchAll(/<img\b([^>]*)>/gi)];
const imageSrcs = imageMatches
  .map((match) => getAttribute(match[1], "src"))
  .filter(Boolean);
const localImageSrcs = imageSrcs.filter((src) => src.startsWith("images/"));
const countedImages = requireLocalImages ? localImageSrcs : imageSrcs;

if (minImages > 0 && countedImages.length < minImages) {
  const label = requireLocalImages ? "local images/ assets" : "image assets";
  errors.push(`Expected at least ${minImages} ${label}, found ${countedImages.length}. CSS diagrams and abstract shapes do not count as real images.`);
}

if (requireLocalImages) {
  const nonLocal = imageSrcs.filter((src) => !src.startsWith("images/"));
  if (nonLocal.length) {
    errors.push(`All images must use relative images/ paths when --require-local-images is set. Non-local sources: ${nonLocal.join(", ")}.`);
  }

  const deckDir = path.dirname(path.resolve(file));
  for (const src of localImageSrcs) {
    const resolved = path.join(deckDir, src);
    if (!fs.existsSync(resolved)) {
      errors.push(`Image path does not exist: ${src}`);
      continue;
    }

    const stat = fs.statSync(resolved);
    if (minImageBytes > 0 && stat.size < minImageBytes) {
      errors.push(`Image asset is smaller than ${minImageBytes} bytes: ${src} (${stat.size} bytes).`);
    }
  }
}

if (errors.length) {
  console.error("Waterfall deck validation failed:");
  for (const error of errors) console.error(`- ${error}`);
  if (warnings.length) {
    console.error("Warnings:");
    for (const warning of warnings) console.error(`- ${warning}`);
  }
  process.exit(1);
}

console.log(`Waterfall deck validation passed: ${totalCards} cards checked.`);
if (warnings.length) {
  console.log("Warnings:");
  for (const warning of warnings) console.log(`- ${warning}`);
}

function countIn(source, pattern) {
  return (source.match(pattern) || []).length;
}

function getAttribute(tagSource, name) {
  const pattern = new RegExp(`${name}\\s*=\\s*(["'])(.*?)\\1`, "i");
  const match = tagSource.match(pattern);
  return match ? match[2] : "";
}
